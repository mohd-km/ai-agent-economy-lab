export type MacroCategory = 'Services' | 'Industry' | 'Primary';
export type CapitalIntensityTier = 'Low' | 'Moderate' | 'High' | 'Very High';

export interface CompanyLeader {
  name: string;
  revenueB: number;
  grossMarginPct: number;
  netMarginPct: number;
  verifiedFY25?: boolean;
}

export interface SubsectorBenchmark {
  code: string;
  name: string;
  revenueB: number;
  volGrowthPct: number;
  valGrowthPct: number;
  cogsPct: number;
  grossMarginPct: number;
  opexPct: number;
  otherPct: number;
  ebitPct: number;
  netMarginPct: number;
  topLeaders: CompanyLeader[];
}

export interface ValueChainStage {
  stage: string;
  role: string;
  shareOfPricePct: number;
  stageMarginPct: number;
  bottleneck: string;
}

export interface ShockSensitivity {
  /** Margin delta in percentage points per +$10/bbl crude oil above $75 baseline */
  oilPer10Usd: number;
  /** Margin delta in percentage points per +100 bps policy rate above 4.5% baseline */
  ratePer100Bps: number;
  /** Margin delta in percentage points per +5 extra shipping chokepoint delay days */
  shippingPer5Days: number;
  /** Revenue volume elasticity (% revenue change) per +100 bps policy rate */
  revRateElasticity: number;
}

export interface MacroSector {
  id: string;
  name: string;
  shortName: string;
  category: MacroCategory;
  /** Value-added GDP contribution in USD trillions (sums to $110.0T global baseline) */
  gdpValueAddedT: number;
  /** Gross revenue across constituent subsectors in USD billions */
  grossRevenueB: number;
  /** Weighted gross margin % */
  grossMarginPct: number;
  /** Weighted operating (EBIT) margin % */
  ebitPct: number;
  /** Implied EBITDA margin % (EBIT + sector-typical D&A add-back) */
  ebitdaPct: number;
  /** Weighted net margin % */
  netMarginPct: number;
  /** Financing, leases, capex & tax drag % */
  financingCapexPct: number;
  capitalIntensity: CapitalIntensityTier;
  assetLifespanNote: string;
  /** YoY value growth % */
  valueGrowthPct: number;
  /** YoY volume growth % */
  volumeGrowthPct: number;
  summary: string;
  sensitivities: ShockSensitivity;
  valueChain: ValueChainStage[];
  subsectors: SubsectorBenchmark[];
}

export interface CountryProfile {
  country: string;
  gdpT: number;
  primaryPct: number;
  secondaryPct: number;
  tertiaryPct: number;
  topSectors: { name: string; sharePct: number; valueT: number; unitFormula: string }[];
}

